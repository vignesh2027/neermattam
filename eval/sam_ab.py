"""SAM 2.1 size comparison on the real photos: small, base-plus and large.

From perception/ (live: Muse Spark Open on Baseten, SAM 2.1 locally):

    uv run --extra local python ../eval/sam_ab.py

Each size runs the full pipeline with the verify-and-refine agent on every photo
in eval/commons_photos.json, in its own process (so its peak memory is its
own), from the same scene readings (kept in eval/out/scene-cache, so every arm
starts from identical boxes and points). The verifier's answers are not
deterministic, so small differences between arms are noise. Results go to
eval/out/ab-<size>/ and the table to eval/RESULTS_SAM_AB.md.

There is no ground truth: "depth reached" counts wheels whose accepted outline
gave a geometry depth, not correct depths. Judge the overlays by eye.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
ARMS = {
    "small": ["--sam-size", "small"],
    "base-plus": ["--sam-size", "base-plus"],
    "large": ["--sam-size", "large"],
    "large-fp16": ["--sam-size", "large", "--fp16"],
    "large-modal": ["--sam-size", "large", "--modal"],
}


def run_arm(name: str, extra: list[str]) -> dict[str, object]:
    out = OUT / f"ab-{name}"
    cmd = [
        sys.executable,
        str(HERE / "real_photos.py"),
        *extra,
        "--out",
        str(out),
        "--scene-cache",
        str(OUT / "scene-cache"),
        "--no-write-results",
    ]
    subprocess.run(cmd, check=True)
    summary: dict[str, object] = json.loads((out / "summary.json").read_text())
    return summary


def table(results: dict[str, dict[str, object]]) -> str:
    lines = [
        "| SAM 2.1 | Wheels checked | Accepted by the verifier | Wheels with a depth | "
        "Per-photo time, median (range) | Peak memory |",
        "|---|---|---|---|---|---|",
    ]
    for s in results.values():
        photos: dict[str, dict[str, object]] = s["photos"]  # type: ignore[assignment]
        checked = sum(int(p["wheels_checked"]) for p in photos.values())  # type: ignore[call-overload]
        accepted = sum(int(p["wheels_accepted"]) for p in photos.values())  # type: ignore[call-overload]
        depths = sum(int(p["wheel_depths"]) for p in photos.values())  # type: ignore[call-overload]
        walls = sorted(float(p["wall_s"]) for p in photos.values())  # type: ignore[arg-type]
        mem: dict[str, float] = s["memory"]  # type: ignore[assignment]
        gpu = (
            f", {mem['mps_driver_mb']:.0f} MB GPU"
            if "mps_driver_mb" in mem
            else " (model on Modal)"
        )
        rate = f"{accepted}/{checked} ({100 * accepted / checked:.0f}%)" if checked else "0/0"
        med = walls[len(walls) // 2] if walls else 0.0
        lines.append(
            f"| {s['sam']} | {checked} | {rate} | {depths} | {med:.0f} s "
            f"({walls[0]:.0f} to {walls[-1]:.0f} s) | {mem.get('peak_rss_mb', 0):.0f} MB process"
            f"{gpu} |"
        )
    return "\n".join(lines)


def per_photo(results: dict[str, dict[str, object]]) -> str:
    names = list(results)
    first: dict[str, object] = results[names[0]]["photos"]  # type: ignore[assignment]
    lines = [
        "| Photo | " + " | ".join(names) + " |",
        "|---|" + "---|" * len(names),
    ]
    for pid in first:
        cells = []
        for n in names:
            p = results[n]["photos"][pid]  # type: ignore[index]
            depth = (
                f"{p['method']} {p['depth_cm']} cm (sigma {p['depth_sigma_cm']}), "
                f"{p['wheels_accepted']}/{p['wheels_checked']} accepted, {p['wall_s']} s"
            )
            cells.append(depth)
        lines.append(f"| {pid} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--arms", nargs="*", default=list(ARMS), choices=list(ARMS))
    args = ap.parse_args(argv)
    results = {name: run_arm(name, ARMS[name]) for name in args.arms}
    body = (
        "# SAM 2.1 size comparison on real photos\n\n"
        f"Generated by `uv run --extra local python ../eval/sam_ab.py` on "
        f"{time.strftime('%Y-%m-%d')}. Every arm starts from the same scene readings; the "
        "verifier is not deterministic. No ground truth: a depth here means an accepted "
        "outline gave a geometry result, not that the result is right.\n\n"
        + table(results)
        + "\n\nPer photo:\n\n"
        + per_photo(results)
        + "\n"
    )
    (HERE / "RESULTS_SAM_AB.md").write_text(body, encoding="utf-8")
    sys.stdout.write(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
