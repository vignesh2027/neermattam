package facts

import (
	"os"
	"path/filepath"
	"reflect"
	"testing"
)

const root = "../../.."

func TestEmbeddedFactsMatchTheDocs(t *testing.T) {
	if _, err := os.Stat(root + "/docs/ENGINE.md"); err != nil {
		t.Skip("docs are not in this build context (the deploy image copies gateway/ only)")
	}
	got, err := Extract(root)
	if err != nil {
		t.Fatal(err)
	}
	if want := Embedded(); !reflect.DeepEqual(got, want) {
		t.Fatalf("facts.json is stale; run `go generate ./internal/facts`.\ndocs say:     %+v\nembedded has: %+v", got, want)
	}
}

func TestEmbeddedFactsAreComplete(t *testing.T) {
	f := Embedded()
	if f.Routing.DryMs == "" || f.Depth.MAECm == "" || f.Real.Photos == 0 || len(f.Trace.Steps) < 3 {
		t.Fatalf("incomplete facts: %+v", f)
	}
	if f.Real.Geometry+f.Real.Person+f.Real.Estimates > f.Real.Photos {
		t.Fatalf("counts do not add up: %+v", f.Real)
	}
}

// The real-photo counts split by method, and a method the gateway does not
// know counts as an estimate, never as a measurement.
func TestRealCountsEveryMethod(t *testing.T) {
	if _, err := os.Stat(root + "/docs/ENGINE.md"); err != nil {
		t.Skip("docs are not in this build context")
	}
	tmp := t.TempDir()
	for _, p := range []string{"docs/ENGINE.md", "docs/GEOMETRY.md", TracePath} {
		b, err := os.ReadFile(filepath.Join(root, p))
		if err != nil {
			t.Fatal(err)
		}
		dst := filepath.Join(tmp, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(dst, b, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	doc := "<!-- real-eval:begin -->\n" +
		"Generated by `uv run --extra local python ../eval/real_photos.py` on 2026-10-30 with muse-spark-open.\n\n" +
		"Result: **wheel_geometry**, depth 20.0 cm, sigma 3.0 cm, confidence 0.6.\n\n" +
		"Result: **person_reference**, depth 49.0 cm, sigma 12.7 cm, confidence 0.23.\n\n" +
		"Result: **person_reference**, depth 72.4 cm, sigma 14.2 cm, confidence 0.16.\n\n" +
		"Result: **model_estimate**, depth 30.0 cm, sigma 20.0 cm, confidence 0.22.\n\n" +
		"Result: **stereo_depth**, depth 30.0 cm, sigma 5.0 cm, confidence 0.5.\n" +
		"<!-- real-eval:end -->\n"
	if err := os.MkdirAll(filepath.Join(tmp, "eval"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(tmp, "eval", "RESULTS_REAL.md"), []byte(doc), 0o644); err != nil {
		t.Fatal(err)
	}
	f, err := Extract(tmp)
	if err != nil {
		t.Fatal(err)
	}
	want := Real{Photos: 5, Geometry: 1, Person: 2, Estimates: 2, Date: "2026-10-30", Source: "eval/RESULTS_REAL.md"}
	if f.Real != want {
		t.Fatalf("got %+v, want %+v", f.Real, want)
	}
	if f.Real.Measured() != 3 {
		t.Fatalf("measured %d", f.Real.Measured())
	}
	if f.Trace.Date != "2026-10-27" || f.Trace.Total != 18 {
		t.Fatalf("trace from the committed fixture: %+v", f.Trace)
	}
}
